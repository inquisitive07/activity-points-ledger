"""The storage interface. PostgreSQL holds document metadata; a Storage holds the bytes under an opaque key.

A key is generated by the server (never derived from a user's filename) and is never sent to clients. Possessing a
key grants nothing: the API only opens a key after loading its Document through permissions.document_scope.
"""
import re
import uuid
from abc import ABC, abstractmethod
from datetime import datetime, timezone
from typing import BinaryIO

# Keys are relative paths of plain segments ("uploads/2026/10/<hex>.pdf", "seed/rvce/x.pdf"). No absolute paths,
# no backslashes, no "." / ".." segments, no empty segments.
_SEGMENT = r"[A-Za-z0-9_-][A-Za-z0-9._-]{0,127}"
KEY_PATTERN = re.compile(rf"{_SEGMENT}(/{_SEGMENT}){{0,7}}")


class StorageError(Exception):
    """A storage operation failed. The message is for logs only; clients get a generic error."""


class InvalidKey(StorageError):
    pass


def check_key(key: str) -> str:
    if not isinstance(key, str) or len(key) > 512 or not KEY_PATTERN.fullmatch(key) \
            or any(part in (".", "..") for part in key.split("/")):
        raise InvalidKey(f"invalid storage key {key!r}")
    return key


def new_key(extension: str) -> str:
    """A fresh, unguessable key. `extension` comes from the verified file signature, not from the filename."""
    now = datetime.now(timezone.utc)
    return check_key(f"uploads/{now:%Y}/{now:%m}/{uuid.uuid4().hex}{extension}")


class Storage(ABC):
    """Replaceable by an S3-compatible implementation with the same four operations."""

    @abstractmethod
    def put(self, key: str, data: bytes) -> None:
        """Store `data` under a new key, atomically: afterwards the object is either complete or absent. Never
        overwrites an existing object."""

    @abstractmethod
    def open(self, key: str) -> BinaryIO:
        """A readable binary stream of the object (the caller closes it). Raises StorageError if it is missing."""

    @abstractmethod
    def exists(self, key: str) -> bool: ...

    @abstractmethod
    def discard(self, key: str) -> None:
        """Remove an object written by an upload whose database transaction failed. This is the only removal: the
        API never physically deletes a stored document (archive and delete are status changes)."""
